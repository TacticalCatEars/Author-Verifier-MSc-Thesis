def calculate_evaluation_metrics(y_true, y_pred):
    """
    Computes overall Accuracy, Precision, Recall, and F1 metrics for
    valid predicted rows (ignoring NaNs).
    """
    # Align arrays and drop missing predictions
    valid_idx = ~np.isnan(y_true) & ~np.isnan(y_pred)
    y_t = np.array(y_true)[valid_idx]
    y_p = np.array(y_pred)[valid_idx]
    
    if len(y_t) == 0:
        return {"Accuracy": 0.0, "Precision": 0.0, "Recall": 0.0, "F1-Score": 0.0, "Evaluated Rows": 0}
        
    # Convert to standard numeric arrays
    y_t = y_t.astype(int)
    y_p = y_p.astype(int)
    
    tp = np.sum((y_t == 1) & (y_p == 1))
    fp = np.sum((y_t == 0) & (y_p == 1))
    fn = np.sum((y_t == 1) & (y_p == 0))
    tn = np.sum((y_t == 0) & (y_p == 0))
    
    accuracy = (tp + tn) / len(y_t)
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = (2 * precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
    
    return {
        "Accuracy": float(accuracy),
        "Precision": float(precision),
        "Recall": float(recall),
        "F1-Score": float(f1),
        "Evaluated Rows": int(len(y_t)),
        "TP": int(tp), "FP": int(fp), "FN": int(fn), "TN": int(tn)
    }

