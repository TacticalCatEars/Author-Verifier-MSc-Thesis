def clean_and_parse_json(raw_response):
    """
    Cleans markdown formatting ticks and preambles from LLM outputs,
    and parses the payload into a structured dictionary.
    """
    cleaned = raw_response.strip()
    
    # Strip common markdown enclosures if present
    if cleaned.startswith("```"):
        # Remove opening block
        if cleaned.startswith("```json"):
            cleaned = cleaned[7:]
        else:
            cleaned = cleaned[3:]
            
        # Remove closing block
        if cleaned.endswith("```"):
            cleaned = cleaned[:-3]
            
    cleaned = cleaned.strip()
    
    # Try to locate the main JSON block if preambles exist
    if not (cleaned.startswith("{") and cleaned.endswith("}")):
        start_idx = cleaned.find("{")
        end_idx = cleaned.rfind("}")
        if start_idx != -1 and end_idx != -1:
            cleaned = cleaned[start_idx:end_idx+1]
            
    # Parse JSON
    try:
        data = json.loads(cleaned)
        # Type validation
        prediction = int(data.get("prediction", 0))
        justification = str(data.get("justification", "No justification parsed."))
        
        # Binary sanitization
        if prediction not in [0, 1]:
            prediction = 1 if prediction > 0.5 else 0
            
        return {"prediction": prediction, "justification": justification, "status": "success"}
    except Exception as e:
        print(f"  [PARSER FAIL] Raw response was: {raw_response}")
        print(f"  [PARSER FAIL] Parse exception: {e}")
        return {
            "prediction": np.nan, 
            "justification": f"Parser failed to resolve JSON. Raw response: {raw_response[:100]}...",
            "status": f"parse_error: {str(e)}"
        }

