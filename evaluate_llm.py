class TimeoutException(Exception):
    pass

def generate_text_with_timeout(model, tokenizer, device, prompt, max_new_tokens=256, timeout_seconds=600):
    """
    Executes model generation in a background thread to prevent lockups.
    Enforces deterministic greedy decoding (do_sample=False) in alignment with Djeffal (2025).
    """
    result_queue = queue.Queue()
    
    def worker():
        try:
            # Enforce deterministic generation params
            inputs = tokenizer(prompt, return_tensors="pt").to(device)
            with torch.no_grad():
                outputs = model.generate(
                    **inputs,
                    max_new_tokens=max_new_tokens,
                    do_sample=False,  # Force greedy search (locks temperature to 0.0)
                    pad_token_id=tokenizer.eos_token_id
                )
            generated_text = tokenizer.decode(outputs[0][inputs.input_ids.shape[1]:], skip_special_tokens=True)
            result_queue.put((generated_text.strip(), "success"))
        except Exception as e:
            result_queue.put((e, "error"))

    # Spawn thread
    thread = threading.Thread(target=worker)
    thread.daemon = True
    thread.start()
    
    try:
        # Wait on queue
        output, status = result_queue.get(timeout=timeout_seconds)
        if status == "error":
            raise output
        return output
    except queue.Empty:
        print(f"\n⚠️  Generation exceeded timeout threshold of {timeout_seconds} seconds. Thread killed.")
        raise TimeoutException("Generation timed out.")

